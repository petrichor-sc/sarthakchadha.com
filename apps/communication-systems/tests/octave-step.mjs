import assert from 'node:assert/strict';
import {simulateUnitStep,unitStepCode} from '../src/octave-step-model.ts';
const base=simulateUnitStep(unitStepCode);
assert.equal(base.times.length,31);
assert.equal(base.times[10],0);
assert.deepEqual(base.values.slice(9,12),[0,1,1]);
assert.equal(base.values.filter(v=>v===1).length,21);
assert.equal(base.times.length,base.values.length);
assert.deepEqual(base.values,base.times.map(t=>Number(t>=0)));
const strict=simulateUnitStep(unitStepCode.replace('t >= 0','t > 0'));
assert.equal(strict.values[10],0);
assert.equal(strict.values.filter((v,i)=>v!==base.values[i]).length,1);
const delayed=simulateUnitStep(unitStepCode.replace('t >= 0','t >= 0.5'));
assert.equal(delayed.times[delayed.values.indexOf(1)],.5);
const coarse=simulateUnitStep(unitStepCode.replace('Ts = 0.1','Ts = 0.2'));
assert.equal(coarse.times.length,16);
assert.equal(coarse.times[coarse.values.indexOf(1)],0);
const negativeOnly=simulateUnitStep(unitStepCode.replace('-1:Ts:2','-2:Ts:-1'));
assert.ok(negativeOnly.values.every(v=>v===0));
const comments=simulateUnitStep(unitStepCode.replace('Ts = 0.1;','Ts = 0.1; % sample interval').replace('Time (seconds)','Time (%)').replace('grid on','grid off'));
assert.equal(comments.grid,false);assert.equal(comments.xlabel,'Time (%)');
for(const bad of [unitStepCode.replace('Ts = 0.1','Ts = 0'),unitStepCode.replace('Ts = 0.1','Ts = -0.1'),unitStepCode.replace('Ts = 0.1','Ts = 0.00001'),unitStepCode.replace('-1:Ts:2','2:Ts:-1'),unitStepCode+'\nalert(1)',unitStepCode.replace('stem(t, u)','plot(t, u)')])assert.throws(()=>simulateUnitStep(bad));
console.log('Passed: unit step at zero, strict comparison, delay, sample interval, vector lengths, labels/grid, and invalid input handling.');
